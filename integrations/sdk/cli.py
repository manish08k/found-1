# ── Class name helper ──────────────────────────────────────────────────────────

def _to_class_name(name: str) -> str:
    """Convert snake_case integration name to PascalCaseIntegration."""
    parts = name.replace("-", "_").split("_")
    pascal = "".join(p.capitalize() for p in parts if p)
    return pascal + "Integration"


# ── CLI entry point ────────────────────────────────────────────────────────────

def _main() -> None:
    import argparse

    parser = argparse.ArgumentParser(
        description="Scaffold a new integration handler.py file.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent("""\
            Examples:
              python -m integrations.sdk.cli --name acme --display-name "Acme Corp" \\
                  --base-url https://api.acme.com/v1 --auth-type bearer

              python -m integrations.sdk.cli --name stripe --display-name Stripe \\
                  --base-url https://api.stripe.com/v1 --auth-type basic \\
                  --output integrations/stripe_/handler.py
        """),
    )
    parser.add_argument("--name", required=True, help="Machine-readable integration name (snake_case)")
    parser.add_argument("--display-name", required=True, help="Human-readable display name")
    parser.add_argument("--base-url", default="", help="API base URL")
    parser.add_argument(
        "--auth-type",
        default="bearer",
        choices=sorted(_VALID_AUTH_TYPES),
        help="Authentication type (default: bearer)",
    )
    parser.add_argument("--category", default="", help="Integration category (e.g. CRM)")
    parser.add_argument("--description", default="", help="Short description")
    parser.add_argument("--output", default=None, help="Output file path (default: stdout)")

    args = parser.parse_args()

    code = generate_integration(
        name=args.name,
        display_name=args.display_name,
        base_url=args.base_url,
        auth_type=args.auth_type,
        category=args.category,
        description=args.description,
    )

    if args.output:
        dest = pathlib.Path(args.output)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(code)
        print(f"Scaffolded integration written to: {dest}", file=sys.stderr)
    else:
        print(code)


if __name__ == "__main__":
    _main()
